"""
Report synthesis and formatting tools.
Permitted tool operations for Agent D (Report Agent).
"""

from typing import Dict, Any, List
from datetime import datetime, timezone

def format_markdown_report(
    title: str,
    executive_summary: str,
    key_findings: List[str],
    statistical_breakdown: Dict[str, Any],
    recommendations: List[str],
    source_references: List[str],
    delegation_context: Dict[str, Any]
) -> str:
    """
    Synthesizes a structured Markdown report with explicit provenance citations.
    """
    ts = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    
    findings_md = "\n".join([f"- **Finding {i+1}:** {f}" for i, f in enumerate(key_findings)])
    recs_md = "\n".join([f"{i+1}. {r}" for i, r in enumerate(recommendations)])
    sources_md = "\n".join([f"- `{src}`" for src in source_references])
    
    stats_rows = []
    for k, v in statistical_breakdown.items():
        if isinstance(v, dict):
            sub = ", ".join([f"{sk}: {sv}" for sk, sv in v.items()])
            stats_rows.append(f"| {k} | {sub} |")
        else:
            stats_rows.append(f"| {k} | {v} |")
    stats_table = "\n".join(stats_rows) if stats_rows else "| Metric | Value |\n|---|---|\n| N/A | N/A |"
    
    report = f"""# {title}

**Generated At:** {ts}  
**Delegation ID:** `{delegation_context.get('delegation_id', 'unknown')}`  
**Originating Principal:** `{delegation_context.get('principal_id', 'unknown')}`  
**Workflow ID:** `{delegation_context.get('workflow_id', 'unknown')}`  

---

## 1. Executive Summary
{executive_summary}

---

## 2. Statistical & Metric Breakdown
| Metric / Dimension | Aggregated Value |
|---|---|
{stats_table}

---

## 3. Key Observable Findings
{findings_md}

---

## 4. Strategic Recommendations
{recs_md}

---

## 5. Provenance & Source Evidence
*The conclusions in this report are backed by explicit recorded telemetry from the following observable sources:*
{sources_md}

---
*Transparency Note: Generated by Multi-Agent Transparency Platform. All actions and communications audited by Central Observability Gateway.*
"""
    return report.strip()


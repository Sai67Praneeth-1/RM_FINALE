import React, { useMemo } from "react";
import { X, Layers, Activity, Bot, ChevronRight } from "lucide-react";

// Relation Edge Colors for styling timeline elements in Google MD3 palette
const RELATION_COLORS = {
  wasDerivedFrom: "#1a73e8",
  used: "#f9ab00",
  wasGeneratedBy: "#1e8e3e",
  wasAssociatedWith: "#5f6368",
  actedOnBehalfOf: "#d93025",
  wasAttributedTo: "#129eaf",
};

export default function ProvenanceDrawer({
  node = null,
  onClose,
  lineagePath = [],
}) {
  const isOpen = Boolean(node);

  // Normalize node type and badge
  const nodeTypeBadge = useMemo(() => {
    if (!node) return { text: "prov:Entity", color: "#1a73e8", bg: "#e8f0fe", border: "#d2e3fc", icon: Layers };

    const raw = String(
      node.prov_category || node.prov_type || node.node_type || node.type || ""
    ).toLowerCase();
    const id = String(node.id || node.entity_id || "").toLowerCase();

    if (
      raw.includes("agent") ||
      id.includes("agent") ||
      id.includes("principal") ||
      id.includes("coordinator")
    ) {
      return {
        text: "prov:Agent",
        color: "#137333",
        bg: "#e6f4ea",
        border: "#ceead6",
        icon: Bot,
      };
    }
    if (
      raw.includes("activity") ||
      raw.includes("tool") ||
      raw.includes("act") ||
      id.includes("evt") ||
      id.includes("tool://")
    ) {
      return {
        text: "prov:Activity",
        color: "#b06000",
        bg: "#fef7e0",
        border: "#feefc3",
        icon: Activity,
      };
    }
    return {
      text: "prov:Entity",
      color: "#1a73e8",
      bg: "#e8f0fe",
      border: "#d2e3fc",
      icon: Layers,
    };
  }, [node]);

  // Derive "Used By" activities from lineage path
  const usedByActivities = useMemo(() => {
    if (!node) return [];
    const nodeId = String(node.id || node.entity_id || "");
    const results = [];

    (lineagePath || []).forEach((edge) => {
      const rel = edge.relation || edge.relation_type || "";
      const src = String(edge.source || edge.source_id || "");
      const tgt = String(edge.target || edge.target_id || "");

      if (rel === "used" && (tgt === nodeId || src === nodeId)) {
        results.push({
          activity: src === nodeId ? tgt : src,
          confidence: edge.confidence ?? 1.0,
          label: edge.target_label || edge.source_label || (src === nodeId ? tgt : src),
        });
      }
    });

    return results;
  }, [node, lineagePath]);

  // Derive "Generated By" activity from lineage path or node properties
  const generatedByActivity = useMemo(() => {
    if (!node) return null;
    const nodeId = String(node.id || node.entity_id || "");

    for (const edge of lineagePath || []) {
      const rel = edge.relation || edge.relation_type || "";
      const src = String(edge.source || edge.source_id || "");
      const tgt = String(edge.target || edge.target_id || "");

      if (
        (rel === "wasGeneratedBy" || rel === "wasAssociatedWith") &&
        (tgt === nodeId || src === nodeId)
      ) {
        return {
          activity: src === nodeId ? tgt : src,
          relation: rel,
          confidence: edge.confidence ?? 1.0,
          label: edge.source_label || edge.target_label || (src === nodeId ? tgt : src),
        };
      }
    }

    if (node.generated_by || node.activity_id) {
      return {
        activity: node.generated_by || node.activity_id,
        relation: "wasGeneratedBy",
        confidence: 1.0,
        label: node.generated_by || node.activity_id,
      };
    }

    return null;
  }, [node, lineagePath]);

  const BadgeIcon = nodeTypeBadge.icon || Layers;

  return (
    <div
      style={{
        position: "fixed",
        top: 0,
        right: 0,
        bottom: 0,
        width: 380,
        maxWidth: "92vw",
        background: "#ffffff",
        borderLeft: "1px solid #dadce0",
        boxShadow: isOpen ? "-4px 0 24px rgba(60, 64, 67, 0.15)" : "none",
        zIndex: 1000,
        display: "flex",
        flexDirection: "column",
        transform: isOpen ? "translateX(0)" : "translateX(100%)",
        transition: "transform 0.28s cubic-bezier(0.16, 1, 0.3, 1)",
        boxSizing: "border-box",
      }}
    >
      {/* Drawer Header */}
      <div
        style={{
          padding: "16px 20px",
          borderBottom: "1px solid #dadce0",
          display: "flex",
          alignItems: "center",
          justifyContent: "space-between",
          background: "#f8f9fa",
        }}
      >
        <div style={{ display: "flex", alignItems: "center", gap: 10 }}>
          <div
            style={{
              padding: "4px 10px",
              borderRadius: 16,
              background: nodeTypeBadge.bg,
              border: `1px solid ${nodeTypeBadge.border}`,
              color: nodeTypeBadge.color,
              fontSize: 11,
              fontWeight: 700,
              letterSpacing: "0.04em",
              display: "flex",
              alignItems: "center",
              gap: 5,
            }}
          >
            <BadgeIcon size={13} />
            <span>{nodeTypeBadge.text}</span>
          </div>
          <span style={{ fontSize: 13, fontWeight: 600, color: "#202124" }}>
            Provenance Inspector
          </span>
        </div>

        <button
          onClick={onClose}
          style={{
            background: "transparent",
            border: "none",
            color: "#5f6368",
            cursor: "pointer",
            padding: 6,
            borderRadius: 20,
            display: "flex",
            alignItems: "center",
            justifyContent: "center",
            transition: "all 0.15s ease",
          }}
          onMouseEnter={(e) => {
            e.currentTarget.style.color = "#202124";
            e.currentTarget.style.background = "#f1f3f4";
          }}
          onMouseLeave={(e) => {
            e.currentTarget.style.color = "#5f6368";
            e.currentTarget.style.background = "transparent";
          }}
          title="Close Drawer"
        >
          <X size={18} />
        </button>
      </div>

      {/* Drawer Body (Scrollable) */}
      <div
        style={{
          flex: 1,
          overflowY: "auto",
          padding: "18px 20px",
          display: "flex",
          flexDirection: "column",
          gap: 20,
          background: "#ffffff",
        }}
      >
        {node && (
          <>
            {/* Node ID & Label */}
            <div>
              <div
                style={{
                  fontSize: 10.5,
                  fontWeight: 700,
                  color: "#5f6368",
                  textTransform: "uppercase",
                  letterSpacing: "0.06em",
                  marginBottom: 4,
                }}
              >
                Node Identifier &amp; Label
              </div>
              <h4
                style={{
                  margin: "0 0 6px 0",
                  color: "#202124",
                  fontSize: 15,
                  fontWeight: 600,
                  wordBreak: "break-word",
                }}
              >
                {node.label || node.name || node.id}
              </h4>
              <div
                style={{
                  background: "#f8f9fa",
                  padding: "6px 10px",
                  borderRadius: 6,
                  border: "1px solid #dadce0",
                  fontFamily: "Roboto Mono, monospace",
                  fontSize: 11,
                  color: "#1a73e8",
                  wordBreak: "break-all",
                }}
              >
                {node.id || node.entity_id}
              </div>
            </div>

            {/* Generated By Section */}
            <div>
              <div
                style={{
                  fontSize: 10.5,
                  fontWeight: 700,
                  color: "#5f6368",
                  textTransform: "uppercase",
                  letterSpacing: "0.06em",
                  marginBottom: 8,
                }}
              >
                Generated By
              </div>
              {generatedByActivity ? (
                <div
                  style={{
                    background: "#e6f4ea",
                    border: "1px solid #ceead6",
                    borderRadius: 8,
                    padding: "10px 12px",
                  }}
                >
                  <div style={{ display: "flex", justifyContent: "space-between", alignItems: "center" }}>
                    <span style={{ fontSize: 12, fontWeight: 600, color: "#137333" }}>
                      {generatedByActivity.label}
                    </span>
                    <span
                      style={{
                        fontSize: 10,
                        background: "#ffffff",
                        color: "#137333",
                        border: "1px solid #ceead6",
                        padding: "1px 6px",
                        borderRadius: 12,
                        fontWeight: 600,
                      }}
                    >
                      {Math.round(generatedByActivity.confidence * 100)}% Conf
                    </span>
                  </div>
                  <div style={{ fontSize: 11, color: "#5f6368", marginTop: 4 }}>
                    <code>{generatedByActivity.activity}</code>
                  </div>
                </div>
              ) : (
                <div
                  style={{
                    fontSize: 12,
                    color: "#5f6368",
                    fontStyle: "italic",
                    background: "#f8f9fa",
                    padding: "8px 12px",
                    borderRadius: 8,
                    border: "1px solid #dadce0",
                  }}
                >
                  Root Entity or External Origin (No generating activity in workflow)
                </div>
              )}
            </div>

            {/* Used By Section */}
            <div>
              <div
                style={{
                  fontSize: 10.5,
                  fontWeight: 700,
                  color: "#5f6368",
                  textTransform: "uppercase",
                  letterSpacing: "0.06em",
                  marginBottom: 8,
                }}
              >
                Used By (Downstream Activities)
              </div>
              {usedByActivities.length > 0 ? (
                <div style={{ display: "flex", flexDirection: "column", gap: 6 }}>
                  {usedByActivities.map((u, idx) => (
                    <div
                      key={idx}
                      style={{
                        background: "#fef7e0",
                        border: "1px solid #feefc3",
                        borderRadius: 8,
                        padding: "8px 12px",
                        display: "flex",
                        justifyContent: "space-between",
                        alignItems: "center",
                      }}
                    >
                      <div>
                        <div style={{ fontSize: 12, fontWeight: 600, color: "#b06000" }}>
                          {u.label}
                        </div>
                        <div style={{ fontSize: 10.5, color: "#5f6368" }}>
                          <code>{u.activity}</code>
                        </div>
                      </div>
                      <span
                        style={{
                          fontSize: 10,
                          background: "#ffffff",
                          color: "#b06000",
                          border: "1px solid #feefc3",
                          padding: "1px 6px",
                          borderRadius: 12,
                          fontWeight: 600,
                        }}
                      >
                        {Math.round(u.confidence * 100)}%
                      </span>
                    </div>
                  ))}
                </div>
              ) : (
                <div
                  style={{
                    fontSize: 12,
                    color: "#5f6368",
                    fontStyle: "italic",
                    background: "#f8f9fa",
                    padding: "8px 12px",
                    borderRadius: 8,
                    border: "1px solid #dadce0",
                  }}
                >
                  No downstream consumption recorded.
                </div>
              )}
            </div>

            {/* Ancestors Lineage Section with Timeline and Confidence Bars */}
            <div>
              <div
                style={{
                  fontSize: 10.5,
                  fontWeight: 700,
                  color: "#5f6368",
                  textTransform: "uppercase",
                  letterSpacing: "0.06em",
                  marginBottom: 10,
                  display: "flex",
                  justifyContent: "space-between",
                  alignItems: "center",
                }}
              >
                <span>Ancestors &amp; Backward Lineage</span>
                <span style={{ color: "#1a73e8", fontWeight: 600 }}>
                  {lineagePath.length} Step{lineagePath.length === 1 ? "" : "s"}
                </span>
              </div>

              {lineagePath.length > 0 ? (
                <div style={{ display: "flex", flexDirection: "column", gap: 10 }}>
                  {lineagePath.map((item, idx) => {
                    const rel = item.relation || item.relation_type || "wasDerivedFrom";
                    const relColor = RELATION_COLORS[rel] || "#5f6368";
                    const conf = Number(item.confidence ?? 1.0);
                    const confPct = Math.round(conf * 100);

                    return (
                      <div
                        key={idx}
                        style={{
                          background: "#ffffff",
                          border: "1px solid #dadce0",
                          borderRadius: 8,
                          padding: "10px 12px",
                          boxShadow: "0 1px 2px rgba(60,64,67,0.08)",
                        }}
                      >
                        {/* Step Sequence Header */}
                        <div
                          style={{
                            display: "flex",
                            justifyContent: "space-between",
                            alignItems: "center",
                            marginBottom: 6,
                          }}
                        >
                          <span
                            style={{
                              fontSize: 11,
                              fontWeight: 600,
                              color: relColor,
                              textTransform: "none",
                            }}
                          >
                            {rel}
                          </span>
                          <span
                            style={{
                              fontSize: 10,
                              fontWeight: 600,
                              color: confPct > 80 ? "#137333" : "#b06000",
                            }}
                          >
                            {confPct}% Confidence
                          </span>
                        </div>

                        {/* Source -> Relation -> Target Flow */}
                        <div
                          style={{
                            display: "flex",
                            alignItems: "center",
                            gap: 6,
                            fontSize: 11.5,
                            color: "#202124",
                            marginBottom: 8,
                          }}
                        >
                          <span
                            style={{
                              overflow: "hidden",
                              textOverflow: "ellipsis",
                              whiteSpace: "nowrap",
                              maxWidth: 120,
                              fontWeight: 600,
                            }}
                            title={item.source_label || item.source}
                          >
                            {item.source_label || item.source}
                          </span>
                          <ChevronRight size={14} color={relColor} />
                          <span
                            style={{
                              overflow: "hidden",
                              textOverflow: "ellipsis",
                              whiteSpace: "nowrap",
                              maxWidth: 120,
                              fontWeight: 600,
                            }}
                            title={item.target_label || item.target}
                          >
                            {item.target_label || item.target}
                          </span>
                        </div>

                        {/* Confidence Progress Bar */}
                        <div
                          style={{
                            width: "100%",
                            height: 4,
                            background: "#f1f3f4",
                            borderRadius: 2,
                            overflow: "hidden",
                          }}
                        >
                          <div
                            style={{
                              width: `${confPct}%`,
                              height: "100%",
                              background: relColor,
                              borderRadius: 2,
                              transition: "width 0.3s ease",
                            }}
                          />
                        </div>
                      </div>
                    );
                  })}
                </div>
              ) : (
                <div
                  style={{
                    fontSize: 12,
                    color: "#5f6368",
                    fontStyle: "italic",
                    background: "#f8f9fa",
                    padding: "8px 12px",
                    borderRadius: 8,
                    border: "1px solid #dadce0",
                  }}
                >
                  No ancestor lineage path available for this element.
                </div>
              )}
            </div>
          </>
        )}
      </div>
    </div>
  );
}
